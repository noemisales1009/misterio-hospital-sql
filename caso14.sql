-- 1) Gatilho de auditoria (chamado CHG-2026-0311, criado pela DBA): só registra, não muda nada
CREATE OR REPLACE FUNCTION ctp_fn_auditoria() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO ctp_auditoria (conta_id, momento, usuario_db,
         valor_bruto_antes, valor_bruto_depois, desconto_antes, desconto_depois,
         valor_final_antes, valor_final_depois)
  VALUES (NEW.id, localtimestamp(0), current_user,
         OLD.valor_bruto, NEW.valor_bruto, OLD.desconto, NEW.desconto,
         OLD.valor_final, NEW.valor_final);
  RETURN NEW;
END;
$$;

CREATE TRIGGER ctp_trg_auditoria
  AFTER UPDATE ON ctp_conta
  FOR EACH ROW
  WHEN (OLD.valor_bruto IS DISTINCT FROM NEW.valor_bruto
     OR OLD.desconto IS DISTINCT FROM NEW.desconto
     OR OLD.valor_final IS DISTINCT FROM NEW.valor_final)
  EXECUTE FUNCTION ctp_fn_auditoria();

