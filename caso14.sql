-- Pacientes particulares (sem convênio)
CREATE TABLE ctp_paciente (
  id             integer PRIMARY KEY,
  nome           text NOT NULL,
  nascimento     date,
  cidade         text,
  cadastrado_em  date
);

-- Contas dos pacientes particulares: o que cada um tem a pagar
CREATE TABLE ctp_conta (
  id           integer PRIMARY KEY,
  paciente_id  integer REFERENCES ctp_paciente(id),
  aberta_em    timestamp,       -- quando a recepção abriu a conta
  tipo         text,            -- 'consulta' · 'exame' · 'cirurgia' · 'internacao'
  descricao    text,
  valor_bruto  numeric(10,2),   -- soma de tudo que foi usado
  desconto     numeric(10,2),   -- desconto em reais (política: no máximo 10% do bruto)
  valor_final  numeric(10,2),   -- valor_bruto - desconto: o que o paciente paga
  status       text             -- 'aberta' ou 'paga'
);

-- Auditoria: o gatilho legítimo grava aqui o ANTES e o DEPOIS de cada UPDATE que muda valores
CREATE TABLE ctp_auditoria (
  id                  serial PRIMARY KEY,
  conta_id            integer,
  momento             timestamp,
  usuario_db          text,          -- quem estava conectado ao banco (current_user)
  valor_bruto_antes   numeric(10,2),
  valor_bruto_depois  numeric(10,2),
  desconto_antes      numeric(10,2),
  desconto_depois     numeric(10,2),
  valor_final_antes   numeric(10,2),
  valor_final_depois  numeric(10,2)
);

-- Usuários (logins) do banco de dados e quem responde por cada um
CREATE TABLE ctp_usuario_db (
  login        text PRIMARY KEY,
  tipo         text,   -- 'pessoal' · 'compartilhada' · 'serviço'
  responsavel  text,   -- a pessoa dona do login (nulo em contas de serviço e compartilhadas)
  descricao    text
);

-- Chamados de mudança: toda alteração de estrutura devia ter um aprovado
CREATE TABLE ctp_chamado (
  codigo        text PRIMARY KEY,
  aberto_em     date,
  solicitante   text,
  descricao     text,
  aprovado_por  text,
  situacao      text
);

-- Log de DDL do banco do hospital inteiro: quem criou/alterou que objeto, quando e de qual máquina
CREATE TABLE ctp_ddl_log (
  id          integer PRIMARY KEY,
  momento     timestamp,
  usuario_db  text,   -- login do banco usado no comando
  maquina     text,   -- nome da estação de onde veio a conexão
  ip          text,
  comando     text,   -- 'CREATE TABLE' · 'CREATE FUNCTION' · 'CREATE TRIGGER' · ...
  objeto      text,   -- nome do objeto criado ou alterado
  tabela      text,   -- tabela envolvida, quando houver
  chamado     text    -- chamado de mudança informado (pode ser nulo)
);

-- Login de rede nas estações: quem estava sentado (ou conectado) em cada máquina
CREATE TABLE ctp_sessao_estacao (
  id          integer PRIMARY KEY,
  pessoa      text,
  login_rede  text,
  maquina     text,
  ip          text,
  inicio      timestamp,
  fim         timestamp,
  via         text    -- 'presencial' ou 'VPN' (de casa, por área de trabalho remota)
);

