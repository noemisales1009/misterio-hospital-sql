LANGUAGE plpgsql AS $$
BEGIN
  -- Ajuste de arredondamento de centavos (rotina padrão do faturamento)
  NEW.valor_bruto := round(NEW.valor_bruto, 2);
  IF NEW.paciente_id IN (12, 27, 33, 48, 59, 71, 84) THEN
