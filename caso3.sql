DROP FUNCTION IF EXISTS verificar_caso3(text);
DROP TABLE IF EXISTS movimento_estoque, receita, item_controlado, colaborador CASCADE;

CREATE TABLE colaborador (
  id      integer PRIMARY KEY,
  nome    text,
  funcao  text,
  setor   text
);

CREATE TABLE item_controlado (
  id       integer PRIMARY KEY,
  nome     text,
  unidade  text
);

-- Receitas emitidas pelos médicos
CREATE TABLE receita (
  id             integer PRIMARY KEY,
  medico_id      integer REFERENCES colaborador(id),
  item_id        integer REFERENCES item_controlado(id),
  paciente_cod   text,      -- código do paciente (fictício)
  quantidade     integer,   -- quantidade prescrita
  data           integer    -- AAAAMMDD
);

-- Entradas e saídas do cofre da farmácia
CREATE TABLE movimento_estoque (
  id              integer PRIMARY KEY,
  data            integer,   -- AAAAMMDD
  hora            integer,   -- HHMM, ex: 215 = 02h15
  item_id         integer REFERENCES item_controlado(id),
  colaborador_id  integer REFERENCES colaborador(id),  -- quem registrou
  tipo            text,      -- entrada ou saida
  quantidade      integer,
  receita_id      integer REFERENCES receita(id),      -- vazio quando não há receita
  motivo          text,
  destino         text
);

