-- Lugares por onde os medicamentos passam
CREATE TABLE lote_local (
  codigo          text PRIMARY KEY,
  nome            text,
  tipo            text,      -- 'almoxarifado' · 'central' · 'satelite' · 'setor'
  ativo           boolean,   -- false = local desativado, não recebe mais nada
  responsavel_id  integer    -- quem responde pelo local (id em lote_funcionario)
);

-- Quem trabalha na cadeia do medicamento, e quem é o chefe de quem
CREATE TABLE lote_funcionario (
  id        integer PRIMARY KEY,
  nome      text,
  cargo     text,
  local     text REFERENCES lote_local(codigo),   -- onde a pessoa trabalha (nulo na diretoria e gerência de enfermagem)
  chefe_id  integer REFERENCES lote_funcionario(id)  -- o chefe direto (nulo para quem está no topo)
);

-- Lotes de medicamento de alto custo que chegaram em setembro e outubro de 2026
CREATE TABLE lote_produto (
  lote          text PRIMARY KEY,
  medicamento   text,
  fabricante    text,
  valor_frasco  numeric(10,2),  -- quanto custa cada frasco, em reais
  qtd_entrada   integer,        -- quantos frascos chegaram do fornecedor
  chegou_em     date
);

-- Rotas autorizadas: de onde para onde um medicamento PODE ser transferido
CREATE TABLE lote_rota (
  origem   text REFERENCES lote_local(codigo),
  destino  text REFERENCES lote_local(codigo),
  tipo     text,   -- 'abastecimento' · 'devolução' · 'empréstimo'
  PRIMARY KEY (origem, destino)
);

-- Guias de transferência. O sistema antigo só anota o lote na PRIMEIRA guia
-- (a entrada, do almoxarifado para a Farmácia Central). Cada guia seguinte
-- diz só de qual guia anterior vieram os frascos (guia_anterior).
CREATE TABLE lote_guia (
  id             integer PRIMARY KEY,
  guia_anterior  integer REFERENCES lote_guia(id),  -- nulo só na guia de entrada do lote
  lote           text REFERENCES lote_produto(lote), -- preenchido só na guia de entrada
  origem         text REFERENCES lote_local(codigo),
  destino        text REFERENCES lote_local(codigo),
  qtd_enviada    integer,   -- frascos que saíram da origem
  qtd_recebida   integer,   -- frascos que quem recebeu contou na chegada
  enviado_em     timestamp,
  recebido_em    timestamp,
  enviado_por    integer REFERENCES lote_funcionario(id),
  recebido_por   integer REFERENCES lote_funcionario(id)   -- quem assinou o recebimento
);

-- Termos de baixa: perdas registradas e justificadas (frasco quebrado etc.)
CREATE TABLE lote_baixa (
  id              integer PRIMARY KEY,
  guia_id         integer REFERENCES lote_guia(id),  -- a guia em que o frasco se perdeu
  qtd             integer,
  motivo          text,
  termo           text,      -- número do termo de baixa assinado
  registrado_por  integer REFERENCES lote_funcionario(id),
  registrado_em   timestamp
);


